// Optional local browser probe. PLAYWRIGHT_MODULE points to a host installation.
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs');
(async () => {
  const browser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH || '/usr/bin/chromium', headless: true, args: ['--no-sandbox'] });
  const page = await browser.newPage({ reducedMotion: 'reduce' });
  const origin = process.env.PROBE_ORIGIN || 'http://localhost:8000';
  const out = process.env.PROBE_OUTPUT || '/tmp/opencode/objectives-review';
  fs.mkdirSync(out, { recursive: true });
  await page.goto(origin);
  await page.evaluate(() => { localStorage.clear(); sessionStorage.clear(); });
  await page.reload();
  await page.locator('.objective-workspace[aria-busy="false"]').waitFor();
  await page.getByRole('button', { name: 'Agregar seleccionados', exact: true }).waitFor();
  for (const width of [1440, 768, 390]) {
    await page.setViewportSize({ width, height: 1000 });
    await page.screenshot({ path: `${out}/home-${width}.png`, fullPage: true });
    assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), `overflow at ${width}`);
  }
  await page.locator('.objective-product').first().getByRole('button', { name: /Aumentar/ }).click();
  await page.locator('.objective-product').last().getByRole('button', { name: 'Quitar', exact: true }).click();
  await page.locator('.hero-catalog-link').focus();
  await page.keyboard.press('Enter');
  await page.waitForURL('**/catalogo');
  await page.goBack();
  await page.locator('.objective-workspace[aria-busy="false"]').waitFor();
  assert.equal(await page.locator('.objective-product input').first().inputValue(), '2');
  assert.equal(await page.locator('.objective-product').count(), 2);
  await page.reload();
  await page.locator('.objective-workspace[aria-busy="false"]').waitFor();
  const quantity = page.locator('.objective-product input').first();
  assert.equal(await quantity.inputValue(), '2');
  await quantity.fill('20');
  await quantity.blur();
  assert(await page.locator('.objective-product').first().getByRole('button', { name: /Aumentar/ }).isDisabled());
  await quantity.fill('');
  assert.equal(await quantity.getAttribute('aria-invalid'), 'true');
  await quantity.blur();
  assert.equal(await quantity.inputValue(), '20');
  await quantity.fill('2');
  await quantity.blur();
  await page.getByRole('button', { name: 'Agregar seleccionados', exact: true }).click();
  await page.waitForFunction(() => JSON.parse(localStorage.getItem('ferready-demo-cart-v1') || '[]').length === 2);
  let cart = await page.evaluate(() => JSON.parse(localStorage.getItem('ferready-demo-cart-v1')));
  assert.equal(cart[0].quantity, 2);
  assert(!cart.some(item => item.slug === 'chazos-tornillo-20'));
  await page.goto(`${origin}/carrito`);
  await page.locator('.cart-item').first().waitFor();
  assert.equal(await page.locator('.cart-item').count(), 2);
  await page.reload();
  await page.locator('.cart-item').first().waitFor();
  assert.equal(await page.locator('.cart-item').count(), 2);
  await page.goto(origin);
  await page.getByRole('button', { name: 'Cuidar mi jardín', exact: true }).click();
  assert.equal(await page.locator('.objective-product').count(), 2);
  await page.locator('.objective-product').first().getByRole('button', { name: 'Quitar', exact: true }).click();
  await page.locator('.objective-product').first().getByRole('button', { name: 'Quitar', exact: true }).click();
  assert(await page.getByRole('button', { name: 'Agregar seleccionados', exact: true }).isDisabled());
  await page.getByRole('button', { name: 'Restablecer selección' }).click();
  assert.equal(await page.locator('.objective-product').count(), 2);
  await page.getByRole('button', { name: 'Abrir menú' }).click();
  assert(await page.locator('.category-nav').isVisible());
  await page.getByRole('searchbox', { name: 'Buscar productos' }).fill('manguera');
  await page.getByRole('button', { name: 'Buscar', exact: true }).click();
  await page.waitForURL('**/catalogo?q=manguera');
  console.log('PASS: 3 responsive screenshots, no overflow; adjust/remove/batch add, persisted cart, goal change, empty/reset, mobile menu and search.');
  await browser.close();
})().catch(error => { console.error(error); process.exit(1); });
