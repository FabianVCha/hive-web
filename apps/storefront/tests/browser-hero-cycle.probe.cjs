const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const assert = require('node:assert/strict');

(async () => {
  const browser = await chromium.launch({ executablePath: '/usr/bin/chromium', args: ['--no-sandbox'] });
  const errors = [];
  const page = await browser.newPage();
  page.on('pageerror', error => errors.push(error.message));
  await page.clock.install();
  const selected = () => page.locator('.hero-object[aria-pressed="true"]').getAttribute('aria-label');
  const tick = async ms => { await page.clock.runFor(ms); };
  const release = async () => {
    await page.mouse.move(0, 0);
    await page.evaluate(() => document.activeElement?.blur());
    await page.waitForTimeout(50);
  };
  for (const width of [390, 1440]) {
    await page.setViewportSize({ width, height: 1000 });
    await page.goto('http://localhost:8000');
    await page.locator('.hero-actions button:not([disabled])').waitFor();
    await release();
    await page.clock.pauseAt(await page.evaluate(() => Date.now()));
    await page.locator('.hero-object').first().dispatchEvent('click', { detail: 1 });
    const first = await selected();
    await tick(9999);
    assert.equal(await selected(), first, 'full ten-second delay');
    await tick(1);
    const second = await selected();
    assert.notEqual(second, first);
    assert.equal(await page.locator('.hero-detail').getAttribute('aria-live'), 'off');
    await tick(10000);
    assert.notEqual(await selected(), second);
    await tick(10000);
    assert.equal(await selected(), first, 'circular wrap');
    await tick(8000);
    await page.locator('.hero-object').first().dispatchEvent('click', { detail: 1 });
    await tick(9999);
    assert.equal(await selected(), first, 'same-item manual reset');
    await tick(1);
    assert.equal(await selected(), second);
    await page.locator('.hero-object').first().focus();
    await page.keyboard.press('Enter');
    await tick(30000);
    assert.equal(await selected(), first, 'keyboard focus pauses');
    assert.equal(await page.locator('.hero-object').first().evaluate(e => e === document.activeElement), true);
    await release();
    await tick(9999);
    assert.equal(await selected(), first);
    await tick(1);
    assert.equal(await selected(), second, 'resume starts fresh');
    await page.getByRole('button', { name: 'Pausar animación' }).click();
    await release();
    await tick(30000);
    assert.equal(await selected(), second, 'explicit pause');
    await page.getByRole('button', { name: 'Activar animación' }).click();
    await release();
    await page.emulateMedia({ reducedMotion: 'reduce' });
    await page.locator('.product-hero[data-idle="paused"]').waitFor();
    await tick(30000);
    assert.equal(await selected(), second, 'reduced motion');
    await page.emulateMedia({ reducedMotion: 'no-preference' });
    await page.locator('.product-hero[data-idle="running"]').waitFor();
    await release();
    await page.locator('.hero-actions button').hover();
    await tick(30000);
    assert.equal(await selected(), second, 'CTA hover pauses');
    await release();
    await page.evaluate(() => window.scrollTo(0, document.body.scrollHeight));
    await page.locator('.product-hero[data-idle="paused"]').waitFor();
    await tick(30000);
    assert.equal(await selected(), second, 'offscreen pauses');
    await page.evaluate(() => window.scrollTo(0, 0));
    await page.locator('.product-hero[data-idle="running"]').waitFor();
    await page.evaluate(() => {
      Object.defineProperty(document, 'hidden', { configurable: true, value: true });
      document.dispatchEvent(new Event('visibilitychange'));
    });
    await page.locator('.product-hero[data-idle="paused"]').waitFor();
    await tick(30000);
    assert.equal(await selected(), second, 'hidden document pauses');
    await page.evaluate(() => {
      delete document.hidden;
      document.dispatchEvent(new Event('visibilitychange'));
    });
    await page.locator('.product-hero[data-idle="running"]').waitFor();
    await tick(9999);
    assert.equal(await selected(), second, 'visibility resume resets countdown');
    await tick(1);
    assert.notEqual(await selected(), second);
    assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
    console.log(`${width}px: 10000ms/wrap/manual reset/focus/pause/reduced motion/hover/offscreen/visibility/overflow passed`);
  }
  assert.deepEqual(errors, []);
  await browser.close();
})().catch(error => { console.error(error); process.exit(1); });
