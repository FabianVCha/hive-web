const { chromium } = require('/home/fabianvcha/playwright-login/node_modules/playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const { execFileSync } = require('node:child_process');
const out = '/tmp/opencode/neutral-template/checkout';
fs.mkdirSync(out, { recursive: true });
(async () => {
  const { products } = (await import('../data/storefront.mjs')).storefront;
  const browser = await chromium.launch({ executablePath: '/usr/bin/chromium', args: ['--no-sandbox'] });
  const page = await browser.newPage({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true });
  const errors = [], writes = [];
  page.on('pageerror', error => errors.push(error.message));
  page.on('request', request => { if (!['GET', 'HEAD'].includes(request.method())) writes.push(request.url()); });
  await page.goto('http://localhost:8000/checkout');
  await page.evaluate(items => localStorage.setItem('ferready-demo-cart-v1', JSON.stringify(items.map(product => ({ slug: product.slug, quantity: 2 })))), products);
  await page.reload();
  await page.getByRole('button', { name: 'Revisar pedido' }).click();
  assert.equal(await page.locator(':focus').getAttribute('name'), 'fullName');
  await page.getByLabel('Nombre completo').fill('Laura Pérez Ñáñez');
  const email = 'laura.' + 'contactomuyextenso'.repeat(5) + '@example.com';
  await page.getByLabel('Correo electrónico').fill(email);
  await page.getByLabel('Teléfono').fill('+57 (300) 000-0000');
  await page.getByLabel('Dirección', { exact: true }).fill('Calle de prueba 123 ' + 'Dirección con caracteres ñ y á '.repeat(5));
  await page.getByLabel('Ciudad o municipio').selectOption('Chía');
  await page.getByLabel('Barrio (opcional)').fill('Barrio de demostración');
  await page.getByLabel('Apartamento, casa u otra indicación (opcional)').fill('Apartamento de prueba');
  await page.evaluate(() => { document.activeElement?.blur(); window.scrollTo(0, 0); });
  await page.screenshot({ path: `${out}/mobile-form.png`, fullPage: true });
  await page.getByRole('button', { name: 'Revisar pedido' }).click();
  assert(await page.getByRole('heading', { name: 'Revisa tu pedido' }).isVisible());
  await page.getByRole('button', { name: 'Editar datos de entrega' }).click();
  await page.getByLabel('Ciudad o municipio').selectOption('Otro municipio');
  await page.getByRole('button', { name: 'Revisar pedido' }).click();
  assert.equal(await page.locator(':focus').getAttribute('name'), 'municipality');
  await page.getByLabel('Nombre del municipio').fill('Municipio de prueba');
  await page.getByRole('button', { name: 'Revisar pedido' }).click();
  assert(await page.locator('.thermal-receipt').getByText('Total parcial sin envío', { exact: true }).isVisible());
  assert((await page.locator('.thermal-receipt').innerText()).includes('Municipio de prueba'));
  await page.getByRole('button', { name: 'Editar datos de entrega' }).click();
  for (const city of ['Bogotá', 'Soacha', 'Chía']) { await page.getByLabel('Ciudad o municipio').selectOption(city); assert((await page.locator('.summary-row').last().innerText()).includes(city === 'Bogotá' ? '12.000' : '18.000')); }
  await page.getByRole('button', { name: 'Revisar pedido' }).click();
  assert.equal(await page.getByRole('button', { name: 'Descargar comprobante PDF' }).count(), 0);
  assert(await page.getByRole('button', { name: 'Simular pago' }).isEnabled());
  const contact = await page.locator('.receipt-contact').innerText();
  for (const label of ['Nombre', 'Correo', 'Teléfono', 'Dirección', 'Ciudad o municipio', 'Barrio', 'Complemento']) assert(await page.locator('.receipt-contact dt').getByText(label, { exact: true }).count());
  assert((await page.locator('.receipt-contact').innerText()).includes(email));
  assert(!(await page.locator('.thermal-receipt').innerText()).includes('Pago de prueba simulado'));
  for (const width of [320, 390, 1440]) {
    await page.setViewportSize({ width, height: 900 });
    await page.evaluate(() => window.scrollTo(0, 0));
    assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), `review overflow at ${width}`);
    assert(await page.locator('.thermal-receipt').evaluate(el => el.scrollWidth <= el.clientWidth), `paper overflow at ${width}`);
    await page.screenshot({ path: `${out}/review-${width}.png`, fullPage: true });
  }
  await page.getByRole('button', { name: 'Simular pago' }).click();
  assert.equal(await page.locator('.receipt-contact').innerText(), contact);
  const receipt = await page.locator('.thermal-receipt').innerText();
  const reference = receipt.match(/DEMO-[a-f0-9-]+/)[0];
  const downloadEvent = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Descargar comprobante PDF' }).click();
  const download = await downloadEvent;
  await download.saveAs(`${out}/order.pdf`);
  const text = execFileSync('pdftotext', ['-layout', `${out}/order.pdf`, '-'], { encoding: 'utf8' });
  fs.writeFileSync(`${out}/order.txt`, text);
  assert(!text.includes('PENDIENTE DE PAGO')); assert(text.includes('PAGO DE PRUEBA SIMULADO')); assert(text.includes('SIN COBRO REAL')); assert(text.includes('NO FISCAL')); assert(text.includes('Laura Pérez Ñáñez')); assert(text.includes('Chía'));
  const info = execFileSync('pdfinfo', [`${out}/order.pdf`], { encoding: 'utf8' });
  assert.match(info, /Page size:\s+226\.77/);
  fs.writeFileSync(`${out}/pdfinfo.txt`, info);
  assert(text.includes(reference)); assert(text.includes('18.000'));
  for (const label of ['Nombre:', 'Correo:', 'Teléfono:', 'Dirección:', 'Ciudad o municipio:', 'Barrio:', 'Complemento:']) assert(text.includes(label), label);
  assert(text.replace(/\s/g, '').includes(email));
  for (const product of products) assert(text.replace(/\s/g, '').includes(product.name.replace(/\s/g, '')), product.name);
  assert.equal(await page.evaluate(() => JSON.parse(localStorage.getItem('ferready-demo-cart-v1')).length), products.length);
  for (const width of [320, 390, 1440]) {
    await page.setViewportSize({ width, height: 900 });
    await page.evaluate(() => window.scrollTo(0, 0));
    assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), `overflow at ${width}`);
    assert(await page.locator('.thermal-receipt').evaluate(el => el.scrollWidth <= el.clientWidth), `paid paper overflow at ${width}`);
    assert(await page.locator('.receipt-contact dd').evaluateAll(fields => fields.every(el => el.scrollWidth <= el.clientWidth)), `contact overflow at ${width}`);
    assert(await page.locator('.thermal-receipt').evaluate(el => parseFloat(getComputedStyle(el).fontSize) >= 13));
    await page.screenshot({ path: `${out}/receipt-${width}.png`, fullPage: true });
  }
  const again = page.waitForEvent('download'); await page.getByRole('button', { name: 'Descargar comprobante PDF' }).click(); assert.equal((await again).suggestedFilename(), `${reference}.pdf`);
  await page.reload(); assert.equal(await page.getByLabel('Nombre completo').inputValue(), '');
   assert(!await page.locator('.thermal-receipt').count());
  assert(!(await page.evaluate(() => JSON.stringify(localStorage) + JSON.stringify(sessionStorage))).includes(email));
  const literalName = '<b>Cliente de prueba</b>';
  await page.getByLabel('Nombre completo').fill(literalName);
  await page.getByLabel('Correo electrónico').fill(email);
  await page.getByLabel('Teléfono').fill('+57 300 000 0000');
  await page.getByLabel('Dirección', { exact: true }).fill('A'.repeat(180));
  await page.getByLabel('Ciudad o municipio').selectOption('Otro municipio');
  await page.getByLabel('Nombre del municipio').fill('Municipio de prueba');
  await page.getByRole('button', { name: 'Revisar pedido' }).click();
  assert.equal(await page.locator('.receipt-contact dt').count(), 5);
  assert((await page.locator('.receipt-contact dd').first().innerText()).includes(literalName));
  assert.equal(await page.locator('.receipt-contact dd b').count(), 0);
  assert((await page.locator('.thermal-receipt').innerText()).includes('Total parcial sin envío'));
  await page.setViewportSize({ width: 320, height: 900 });
  assert(await page.locator('.receipt-contact dd').evaluateAll(fields => fields.every(el => el.scrollWidth <= el.clientWidth)));
  await page.screenshot({ path: `${out}/unknown-city-review-320.png`, fullPage: true });
  await page.getByRole('button', { name: 'Simular pago' }).click();
  const unknownDownload = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Descargar comprobante PDF' }).click();
  await (await unknownDownload).saveAs(`${out}/unknown-city.pdf`);
  const unknownText = execFileSync('pdftotext', ['-layout', `${out}/unknown-city.pdf`, '-'], { encoding: 'utf8' });
  assert(unknownText.includes('TOTAL PARCIAL SIN ENVÍO'));
  assert(unknownText.includes(literalName));
  assert(!unknownText.includes('Barrio:')); assert(!unknownText.includes('Complemento:'));
  await page.emulateMedia({ media: 'print' });
  assert.equal(await page.locator('.thermal-receipt').evaluate(el => getComputedStyle(el).color), 'rgb(0, 0, 0)');
  assert.equal(await page.locator('.thermal-receipt').evaluate(el => getComputedStyle(el).maskImage), 'none');
  await page.emulateMedia({ media: 'screen' });
  await page.evaluate(() => localStorage.setItem('ferready-demo-cart-v1', '[]')); await page.reload();
  await page.getByRole('heading', { name: 'Primero elige tus productos.' }).waitFor();
  assert.deepEqual(errors, []); assert.deepEqual(writes, []);
  fs.writeFileSync(`${out}/report.json`, JSON.stringify({ reference, errors, writes, widths: [320, 390, 1440], cartPreserved: true, privateFieldsPersisted: false }, null, 2));
  await browser.close(); console.log('Guest checkout, validation, editing, coverage, actual PDF, cart preservation and reload passed');
})().catch(error => { console.error(error); process.exit(1); });
